export type CardKind = "action" | "event";

export interface CardDef {
  id: string;
  label: string;
  kind: CardKind;
  effect: string;
  price?: string;
  /** Короткое описание НЕГАТИВНОГО эффекта, который срабатывает, если ИМЕННО эта карта уходит в
   * вынужденный сброс руки (≥8 карт, см. GameSession.resolveHandOverflowDiscard) — по прямому
   * запросу («в инструкциях отдельным заголовком должен быть описан негативный эффект карты при
   * сбросе... описания должны содержать короткий положительный эффект и цену, короткий отрицательный
   * эффект при сбросе»). У КАЖДОЙ карты (и действия, и события) есть своя ветка в
   * resolveHandOverflowDiscard — если ветки нет (`trader`/`worker`), здесь явно «Эффекта нет.», а не
   * отсутствие поля, чтобы в интерфейсе не выглядело забытым/недописанным. */
  discardEffect: string;
  /** Event cards can never be discarded — their effect resolves automatically instead (ТЗ 2.3). */
  discardable: boolean;
  /** Кто отдал ИМЕННО ЭТОТ экземпляр карты текущему держателю через обязательную передачу (ТЗ
   * 2.3) — не тот же самый игрок, что и вообще «последний, кто мне что-то давал»: у игрока может
   * быть несколько карт в руке, каждая со своей (или вовсе без) историей. `undefined`/`null` — эта
   * карта не из передачи (пришла с колоды или куплена на рынке). Очищается, когда карта уходит на
   * дно колоды (сыграна/сброшена) — иначе метка ложно пережила бы карту до следующей раздачи
   * совсем другому игроку. См. GameSession.handoffCard. */
  receivedFrom?: number | null;
  /** Только у карты «Право прокладки маршрута» (см. GameSession.pickRouteCities/playRouteRightCard,
   * по прямому уточнению «если маршрут некуда было проложить, право превращается в карту в руке»):
   * технология и тип маршрута, которые надо разыграть при повторной попытке. Эта карта не часть
   * колоды (freshDeck её не создаёт, минтится напрямую), не занимает место в лимите руки (см.
   * GameSession.handCountedSize) и при неудачной попытке остаётся в руке для повторной попытки. */
  routeTechId?: string;
  routeCategory?: "land" | "sea" | "universal";
  /** Только у бесплатного «Рабочего» парадигмы Монархия (см. GameSession.grantMonarchyWorkerCards,
   * по прямому запросу): минтится напрямую (не из колоды). По прямому уточнению («иначе имбово со
   * Складом») СЧИТАЕТСЯ в лимит руки (фактически 7 → 6 обычных карт, пока лежит в руке) и уходит в
   * обычный вынужденный сброс при переполнении наравне с другими картами, но НЕ защищает от
   * негативного эффекта сброса (нейтрализация «в сбросе есть Рабочий» — только от настоящего). Не
   * передаётся другому игроку и не продаётся (см. handoffCard/sellCard); не уходит в общую колоду
   * при розыгрыше/сбросе (см. consumeHandCard/resolveHandOverflowDiscard) — просто исчезает,
   * обновляется заново каждый цикл. Рисуется с другой рубашкой в клиенте (main.ts) — чтобы
   * отличаться от обычных карт «Рабочий». */
  freeMonarchy?: boolean;
  /** Тот же приём, что и freeMonarchy выше, только для Фашизма и карты «Воин» (по прямому запросу —
   * «вместо х2 юнита сделать по аналогии с рабочим в монархии»: замена прежнего бонуса «Воин строит
   * сразу 2 юнита» на бесплатную карту «Воин», всегда доступную в руке, пока действует парадигма, и
   * восполняемую в начале следующего цикла, если была разыграна). Во всём остальном ведёт себя как
   * freeMonarchy (см. GameSession.grantFascismWarriorCards, handoffCard/sellCard/consumeHandCard/
   * resolveHandOverflowDiscard) — считается в лимит руки, не защищает от негативного эффекта сброса,
   * не передаётся и не продаётся, не возвращается в общую колоду при уходе из руки. */
  freeFascism?: boolean;
  /** Бонус первооткрывателя технологии «Образование» (по прямому запросу — «карта учёного с золотой
   * рубашкой как у рабочего из монархии») — 1 бесплатная карта «Учёный» (id тот же "scientist", та
   * же кнопка/модалка выбора технологии), минтится напрямую при открытии технологии, НЕ из колоды.
   * В отличие от freeMonarchy/freeFascism — одноразовая, не восполняется каждый цикл (см.
   * GameSession.grantSingleTech). Розыгрыш (GameSession.playFreeEducationCard) бесплатен и по
   * ресурсам, И по действию (доступен даже при 0 действий, тем же приёмом, что routeRight) — этим
   * отличается от Монархии/Фашизма, где сама КАРТА бесплатна, но её розыгрыш всё ещё стоит действие.
   * Считается в лимит руки и сбрасывается наравне с обычными (не защищена, не передаётся, не
   * продаётся) — тот же принцип, что у freeMonarchy/freeFascism. */
  freeEducation?: boolean;
  /** Бонус первооткрывателя технологии «Архитектура» (по прямому запросу — «первооткрыватель
   * бесплатное здание получит, выбрать из списка доступных сейчас на момент открытия») — 1
   * бесплатная карта «Строитель» (id тот же "builder", та же кнопка «Открыть стройку»/панель зданий),
   * минтится напрямую при открытии технологии, НЕ из колоды. Тот же приём, что и freeEducation
   * выше: розыгрыш (GameSession.playFreeBuildingCard) бесплатен и по ресурсам, и по действию;
   * одноразовая, не восполняется каждый цикл; считается в лимит руки, не защищена от сброса, не
   * передаётся и не продаётся. В отличие от обычного «Строителя» — только постройка здания
   * (альтернативные применения «Добыть силикат»/«Срубить лес» этой картой недоступны, бонус
   * конкретно про здание). */
  freeBuilding?: boolean;
  /** Парламентаризм (по прямому запросу — «сделай постоянную карту строителя как рабочий у
   * монархии») — 1 бесплатная карта «Строитель» в руке, тот же приём, что и freeMonarchy/
   * freeFascism выше (см. GameSession.grantParliamentarismBuilderCards): обновляется каждый цикл,
   * пока действует парадигма и в руке нет неразыгранной такой карты; считается в лимит руки, не
   * защищает от негативного эффекта сброса, не передаётся и не продаётся, не возвращается в общую
   * колоду при уходе из руки. Обычный «Строитель» (не freeBuilding выше — та однократная, от
   * технологии «Архитектура») — все альтернативные применения карты доступны как всегда. */
  freeParliamentarism?: boolean;
  /** «Учёный», выбор 4 из 4 эндгейм-эффектов, доступных после того, как ВСЕ технологии партии уже
   * открыты этим игроком (по прямому запросу, см. GameSession.useScientistEndgameEffect) — 2
   * бесплатные карты «Рост леса» в руке разом, минтятся напрямую, НЕ из колоды. Тот же приём, что и
   * freeEducation/freeBuilding: розыгрыш (GameSession.plantFreeForest) бесплатен и по ресурсам, и
   * по действию; одноразовые (каждая расходуется по отдельности), не восполняются; считаются в
   * лимит руки, не защищены от сброса, не передаются и не продаются. */
  freeForestGrowth?: boolean;
}

/** Минтится напрямую (не из колоды) когда исследованная маршрутная технология не смогла проложить
 * путь ни к одному городу — см. GameSession.pickRouteCities. */
