/** Монархия (по прямому запросу, заменяет старую защиту юнитов ×2) — 1 бесплатная карта «Рабочий» в
 * руке, минтится напрямую (не из колоды, как и makeRouteRightCard выше), помечена `freeMonarchy`.
 * Играется и работает как обычный «Рабочий» (тот же card.id === "worker", та же кнопка/логика) —
 * копирует label/effect/price с ACTION_CARDS, чтобы текст не расходился с обычной картой. */
export function makeMonarchyWorkerCard(): CardDef {
  const base = ACTION_CARDS.find((c) => c.id === "worker")!;
  return { ...base, freeMonarchy: true };
}

/** Фашизм (по прямому запросу, заменяет прежний бонус «Воин строит сразу 2 юнита за ту же цену») —
 * 1 бесплатная карта «Воин» в руке, тем же приёмом, что и makeMonarchyWorkerCard выше: минтится
 * напрямую, помечена `freeFascism`, копирует label/effect/price с ACTION_CARDS. */
export function makeFascismWarriorCard(): CardDef {
  const base = ACTION_CARDS.find((c) => c.id === "warrior")!;
  return { ...base, freeFascism: true };
}

/** Число копий по типу карты — по умолчанию 4 у карт действия и 2 у карт событий (ТЗ 3), но
 * «Рабочий»/«Учёный» подняты по прямому уточнению (8 и 6; «Воин» сначала тоже подняли до 6, потом
 * вернули обратно на 4 по уточнению). «Воин»/«Поселенец» подняты ЕЩЁ РАЗ, теперь до 6 каждая — по
 * прямому запросу («колода на 42 карты, не хватает на 6 игроков — добавь по 2 Воина и 2 Поселенца»).
 * Остальные карты действия и все карты событий на дефолте — итоговая колода теперь
 * 24+(8-4)+(6-4)+(6-4)+(6-4)+12 = 46. */
const CARD_COPIES: Partial<Record<string, number>> = { worker: 8, scientist: 6, warrior: 6, settler: 6 };
const DEFAULT_ACTION_COPIES = 4;
const DEFAULT_EVENT_COPIES = 2;

/** Полная колода (ТЗ 3, число карт теперь НЕ строго 36 — см. CARD_COPIES выше). Каждая копия —
 * СВОЙ объект (`{...card}`), не общая ссылка на один из 12 элементов ACTION_CARDS/EVENT_CARDS:
 * нужно для receivedFrom (ТЗ 2.3, обязательная передача) — без клонирования пометка на одной
 * физической карте задела бы сразу все копии того же типа где угодно в игре. */
export function freshDeck(): CardDef[] {
  const deck: CardDef[] = [];
  for (const card of ACTION_CARDS) {
    const count = CARD_COPIES[card.id] ?? DEFAULT_ACTION_COPIES;
    for (let i = 0; i < count; i++) deck.push({ ...card });
  }
  for (const card of EVENT_CARDS) {
    const count = CARD_COPIES[card.id] ?? DEFAULT_EVENT_COPIES;
    for (let i = 0; i < count; i++) deck.push({ ...card });
  }
  return deck;
}

/** `rng` — необязательный (по умолчанию Math.random, как раньше); сервер (web/server) передаёт
 * свой детерминированный RNG сессии явно, чтобы тасовка колоды тоже была воспроизводима. */
export function shuffle<T>(arr: T[], rng: () => number = Math.random): T[] {
  const copy = arr.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
