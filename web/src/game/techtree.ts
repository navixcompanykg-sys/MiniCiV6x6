export function techsAt(epoch: TechDef["epoch"], branch: TechDef["branch"]): TechDef[] {
  return TECH_TREE.filter((t) => t.epoch === epoch && t.branch === branch);
}

/** True once every technology in a branch has a defined effect — the branch "закрыта" (done). */
export function isBranchComplete(branch: TechDef["branch"]): boolean {
  return TECH_TREE.filter((t) => t.branch === branch).every((t) => t.hasEffect);
}

/** Сколько технологий ветки ещё без эффекта — для счётчика в заголовке колонки. */
export function branchGaps(branch: TechDef["branch"]): number {
  return TECH_TREE.filter((t) => t.branch === branch && !t.hasEffect).length;
}
