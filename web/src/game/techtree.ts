export interface TechDef {
  id: string;
  name: string;
  epoch: 1 | 2 | 3 | 4 | 5 | 6;
  branch: 0 | 1 | 2 | 3;
  /** Основная категория — первый тег технологии в Технологии.md. Красит узел в дереве. */
  cat: TechCat;
  /** Полная строка тегов из Технологии.md — показывается в подсказке. */
  tags: string;
  /** Уникальная технология (🔓) в дизайне — задумана как «достаётся только лидеру ветки», но эта
   * проверка нигде не реализована в GameSession.ts: любой исследовавший получает эффект как обычно.
   * Флаг сейчас влияет только на иконку 🔓 в дереве, не на геймплей. */
  unique: boolean;
  /** Технология открывает здание (🏛) — см. unitsUnlockedBy/buildingsUnlockedBy ниже. */
  building: boolean;
  /** Технология даёт торговый маршрут этого типа — определяет, по каким тайлам его можно
   * прокладывать (GameSession.findRoutePath): land — только суша, sea — только море (не лёд),
   * universal — выбирается более короткий из двух чистых вариантов (весь путь по суше ИЛИ весь по
   * морю, без смешения в одном маршруте), Финансовый/Авиация/Космонавтика. undefined — маршрута нет.
   * Доступ к типу маршрута получает КАЖДЫЙ исследовавший технологию; бесплатная карта «Право
   * прокладки маршрута» — только первооткрывателю, см. founderBonus. */
  route?: "land" | "sea" | "universal";
  /** Краткое описание ТОЛЬКО «прочих» эффектов — то, что не выводится автоматически из юнитов/
   * зданий/лимита города/бонуса первооткрывателю/ресурсов/улучшения стандартной карты/дипинструмента:
   * разблокировки парадигм, тип маршрута, уникальные способности вне остальных категорий. Пустая
   * строка — у технологии нет эффектов вне структурированных категорий. */
  summary: string;
  /** Даёт право ПРЕДЛАГАТЬ этот тип дипломатического соглашения (`GameSession.AGREEMENT_META` —
   * технология отправителя проверяется в `sendProposal`) — не путать с ПАРАДИГМОЙ (та не про
   * соглашения между игроками, см. summary) и не с мгновенной дипломатией (Мир/Война — доступны с
   * кем угодно всегда, без технологии). undefined — у технологии нет дипломатического инструмента.
   * Ровно 6 технологий по числу соглашений: Письменность/Феодализм/Кодекс законов/Гильдии/
   * Книгопечатание/Коммунизм. */
  diplomacyTool?: string;
  /** Бонус ЛИЧНОМУ первооткрывателю (isFirstDiscovery в GameSession.grantSingleTech) — разовый
   * (население/деньги/контент), постоянный до конца партии (снижение содержания/бонус урона или
   * дальности), бесплатная карта маршрута или право основать религию. undefined — у технологии нет
   * бонуса первооткрывателю. Открытие технологии повторно (после кого-то другого) даёт юниты/здания/
   * лимит города как обычно, но НЕ этот бонус. */
  founderBonus?: string;
  /** Открывает доступ к добыче ресурсов определённого класса ИЛИ удваивает частоту их добычи
   * («Рабочий» может добыть тот же ресурс дважды за цикл, не больше за раз) — см.
   * `GameSession.resourceIsExtractable`/`resourceGatherMultiplier` (там же и исчерпывающий список).
   * undefined — у технологии нет эффекта на добычу ресурсов. */
  resourceEffect?: string;
  /** Даёт ОДНОЙ из 6 стандартных карт действия (Поселенец/Воин/Строитель/Рабочий/Учёный/Торговец)
   * новое альтернативное применение, которого без этой технологии у карты нет (не путать с
   * resourceEffect выше — удвоение добычи не добавляет новый пункт выбора карте, только позволяет
   * добыть повторно). undefined — у технологии нет такого эффекта. Полный список — grep
   * `card.id !== "..."` рядом с `researchedTechs` в GameSession.ts. */
  cardUpgrade?: string;
  /** Есть ли у технологии определённый игровой эффект (юниты/здание/маршрут/ресурсы/дипломатия/
   * парадигма) — технологии без эффекта ещё не спроектированы, см. "Сводка пустых мест" в
   * Технологии.md. Используется только для подсветки пробелов в дереве, не влияет на геймплей. */
  hasEffect: boolean;
}

interface TechOpts {
  unique?: boolean;
  building?: boolean;
  route?: "land" | "sea" | "universal";
  founderBonus?: string;
  resourceEffect?: string;
  cardUpgrade?: string;
  diplomacyTool?: string;
  hasEffect?: boolean;
}

