export function techsAt(epoch: TechDef["epoch"], branch: TechDef["branch"]): TechDef[] {
  return TECH_TREE.filter((t) => t.epoch === epoch && t.branch === branch);
}

/** Юниты, которые открывает эта технология (UnitDef.tech === techId). Не включает юниты с
 * tech: null (доступны всем без исследований, например «Воин»). */
export function unitsUnlockedBy(techId: string): UnitDef[] {
  return UNITS.filter((u) => u.tech === techId);
}

/** Здания, которые открывает эта технология (BuildingDef.tech === techId) — обычно одно, но
 * «Атомная энергия» открывает сразу два (АЭС и Ядерный арсенал). */
export function buildingsUnlockedBy(techId: string): BuildingDef[] {
  return BUILDINGS.filter((b) => b.tech === techId);
}

/** Структурированный список эффектов технологии, в фиксированном порядке: Юниты → Здания → Город →
 * Ресурсы → Улучшение карты → Дипинструмент → «прочее» (t.summary) → Первооткрывателю. Общий
 * источник для подсказки в дереве технологий и для списка в модалке «Учёный» (main.ts) — раньше
 * собирались по отдельности и расходились. */
export function techEffectLines(t: TechDef): string[] {
  const lines: string[] = [];
  const units = unitsUnlockedBy(t.id);
  if (units.length) lines.push(`⚔ Юниты: ${units.map((u) => u.name).join(", ")}`);
  for (const b of buildingsUnlockedBy(t.id)) lines.push(`🏛 ${b.name}: ${b.effect}`);
  if (CITY_CAPACITY_TECHS.includes(t.id)) lines.push("🏙 Вместимость города +1 (база 1, максимум +5 со всех 5 технологий)");
  if (t.resourceEffect) lines.push(`⛏ ${t.resourceEffect}`);
  if (t.cardUpgrade) lines.push(`🃏 ${t.cardUpgrade}`);
  if (t.diplomacyTool) lines.push(`🤝 Дипломатия: ${t.diplomacyTool}`);
  if (t.summary) lines.push(t.summary);
  if (t.founderBonus) lines.push(`🔑 Первооткрывателю: ${t.founderBonus}`);
  if (!t.hasEffect) lines.push("⚠ Эффект пока не спроектирован");
  return lines;
}

/** True once every technology in a branch has a defined effect — the branch "закрыта" (done). */
export function isBranchComplete(branch: TechDef["branch"]): boolean {
  return TECH_TREE.filter((t) => t.branch === branch).every((t) => t.hasEffect);
}

/** Сколько технологий ветки ещё без эффекта — для счётчика в заголовке колонки. */
export function branchGaps(branch: TechDef["branch"]): number {
  return TECH_TREE.filter((t) => t.branch === branch && !t.hasEffect).length;
}
