export interface RefEntry {
  id: string;
  title: string;
  category: RefCategory;
  /** Короткая строка под заголовком в списке результатов. */
  summary: string;
  /** Полное описание механики — показывается при открытии статьи. Обычный текст, \n\n = абзац. */
  body: string;
  /** Доп. слова для поиска, не показываются (синонимы, категория на русском, эпоха и т.п.). */
  tags: string[];
}

const entries: RefEntry[] = [];

// --- Юниты (36, из units.ts) --------------------------------------------------------------------
for (const u of UNITS) {
  const meta = CATEGORY_META[u.category];
  const s = statsFor(u.category, u.epoch);
  const lines = [
    `Категория: ${meta.label} (эпоха ${u.epoch}).`,
    u.tech ? `Технология: «${u.tech}».` : "Доступен всем с самого начала партии, без технологии.",
    `HP ${s.hp} · Атака ${s.attack || "—"} · Дальность атаки ${s.attackRange || "—"} · Ход ${s.moveRange}.`,
  ];
  if (s.aoe) lines.push("Бьёт по ВСЕМ юнитам клетки-цели сразу (AoE), не по одному.");
  if (s.supportBonus) lines.push(`Даёт +${s.supportBonus} к урону союзных Штурмовых/Мобильных юнитов в радиусе ${s.supportRadius} — сам не атакует.`);
  if (s.armorMultiplier > 1) lines.push(`Множитель к собственной защите: ×${s.armorMultiplier}.`);
  if (u.category === "ship") lines.push("Плавающая артиллерия — растущая с эпохой атака, AoE, без поддержки; переправляет 1 сухопутный юнит как мост.");
  entries.push({
    id: `unit:${u.id}`,
    title: u.name,
    category: "unit",
    summary: `${meta.label}, эпоха ${u.epoch}${u.tech ? ` · ${u.tech}` : ""}`,
    body: lines.join("\n\n"),
    tags: [meta.label, `эпоха ${u.epoch}`, u.category],
  });
}

