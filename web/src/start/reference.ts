/** Простой регистронезависимый поиск подстрокой по названию/тегам/тексту — совпадение в названии
 * ранжируется выше совпадения только в теле статьи. Пустой запрос возвращает всё (для просмотра по
 * категориям без ввода текста). */
export function searchReference(query: string, category: RefCategory | null): RefEntry[] {
  const q = query.trim().toLowerCase();
  let pool = category ? REFERENCE.filter((e) => e.category === category) : REFERENCE;
  if (!q) return pool;
  const scored = pool
    .map((e) => {
      const title = e.title.toLowerCase();
      const haystack = `${e.summary} ${e.body} ${e.tags.join(" ")}`.toLowerCase();
      let score = 0;
      if (title === q) score = 3;
      else if (title.startsWith(q)) score = 2;
      else if (title.includes(q)) score = 1;
      else if (haystack.includes(q)) score = 0.5;
      else return null;
      return { e, score };
    })
    .filter((x): x is { e: RefEntry; score: number } => x !== null);
  scored.sort((a, b) => b.score - a.score || a.e.title.localeCompare(b.e.title, "ru"));
  return scored.map((x) => x.e);
}
